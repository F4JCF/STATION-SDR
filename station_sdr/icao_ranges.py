def icao_country(hex_addr):
    """(nom du pays, code ISO) pour une adresse ICAO hexadécimale, ou (None, None)."""
    try:
        v = int(str(hex_addr).strip().lstrip("~"), 16)
    except (TypeError, ValueError):
        return None, None
    for start, end, name, code in ICAO_RANGES:
        if start <= v <= end:
            return name, code
    return None, None
